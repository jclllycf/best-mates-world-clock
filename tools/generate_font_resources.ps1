# Generates res/font family XMLs for bundled fonts and TextClock layouts for live system styles.
# Keep this table in sync with WidgetFonts.kt (the Kotlin registry is the source of truth for IDs/labels).
# Usage (from repository root): powershell -File tools/generate_font_resources.ps1
$ErrorActionPreference = "Stop"
$res = Join-Path $PSScriptRoot "..\app\src\main\res"

# key, font file resource, fontWeight, variation settings
$fonts = @(
    @("figtree_light", "figtree_vf", 300, "'wght' 300"),
    @("figtree", "figtree_vf", 500, "'wght' 500"),
    @("figtree_bold", "figtree_vf", 760, "'wght' 760"),
    @("sora", "sora_vf", 400, "'wght' 400"),
    @("space_grotesk", "space_grotesk_vf", 500, "'wght' 500"),
    @("bricolage", "bricolage_vf", 640, "'wght' 640, 'wdth' 88, 'opsz' 48"),
    @("syne", "syne_vf", 700, "'wght' 700"),
    @("unbounded", "unbounded_vf", 500, "'wght' 500"),
    @("oswald", "oswald_vf", 500, "'wght' 500"),
    @("fraunces", "fraunces_vf", 520, "'wght' 520, 'opsz' 72, 'SOFT' 100"),
    @("fraunces_fine", "fraunces_vf", 300, "'wght' 300, 'opsz' 144, 'SOFT' 50"),
    @("instrument_serif", "instrument_serif", 400, ""),
    @("dm_serif", "dm_serif_display", 400, ""),
    @("young_serif", "young_serif", 400, ""),
    @("playfair", "playfair_vf", 600, "'wght' 600"),
    @("nunito", "nunito_vf", 700, "'wght' 700"),
    @("baloo", "baloo2_vf", 600, "'wght' 600"),
    @("jetbrains_mono", "jetbrains_mono_vf", 420, "'wght' 420"),
    @("silkscreen", "silkscreen", 400, ""),
    @("caveat", "caveat_vf", 600, "'wght' 600"),
    @("pacifico", "pacifico", 400, "")
)

$utf8 = New-Object System.Text.UTF8Encoding($false)
foreach ($f in $fonts) {
    $key = $f[0]; $file = $f[1]; $weight = $f[2]; $axes = $f[3]
    $axesAttr = if ($axes) { "`n        android:fontVariationSettings=`"$axes`"" } else { "" }
    $family = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_font_resources.ps1. Do not edit by hand. -->
<font-family xmlns:android="http://schemas.android.com/apk/res/android">
    <font
        android:font="@font/$file"
        android:fontStyle="normal"
        android:fontWeight="$weight"$axesAttr />
</font-family>
"@
    [System.IO.File]::WriteAllText((Join-Path $res "font\bmf_$key.xml"), $family, $utf8)
}

# Live time/date styles. Launchers inflate widget layouts in a restricted context that
# ignores app font resources, so TextClocks use system families at explicit weights
# (android:textFontWeight is honoured there). Keep in sync with WidgetFonts.live.
$live = @(
    @("sans_thin", "sans-serif", 200), @("sans_light", "sans-serif", 300), @("sans", "sans-serif", 400),
    @("sans_medium", "sans-serif", 500), @("sans_bold", "sans-serif", 700), @("sans_black", "sans-serif", 900),
    @("condensed_light", "sans-serif-condensed", 300), @("condensed", "sans-serif-condensed", 400),
    @("condensed_bold", "sans-serif-condensed", 700), @("serif", "serif", 400), @("serif_bold", "serif", 700),
    @("mono", "monospace", 400), @("script", "cursive", 700), @("casual", "casual", 400)
)
foreach ($l in $live) {
    $key = $l[0]; $family = $l[1]; $weight = $l[2]
    $style = if ($weight -ge 600) { "bold" } else { "normal" }
    $clock = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_font_resources.ps1. Live clock text, system "$family" at weight $weight. -->
<TextClock xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/clock"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:fontFamily="$family"
    android:gravity="center"
    android:includeFontPadding="false"
    android:maxLines="1"
    android:textColor="#FFFFFFFF"
    android:textFontWeight="$weight"
    android:textSize="16dp"
    android:textStyle="$style" />
"@
    [System.IO.File]::WriteAllText((Join-Path $res "layout\widget_clock_sys_$key.xml"), $clock, $utf8)
}
Write-Output "Generated $($fonts.Count) font families and $($live.Count) live clock layouts."
